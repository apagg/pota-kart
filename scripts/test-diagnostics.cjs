const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'../diagnostics.js'),'utf8');
const logged=[];
const context=vm.createContext({console:{warn:(...x)=>logged.push(x),error:(...x)=>logged.push(x)},Date});
vm.runInContext(source,context);
const api=vm.runInContext('potaDiagnostics',context);
api.report('atlas/test',new Error('offline'));
assert.equal(api.recent().length,1);
assert.equal(api.recent()[0].message,'offline');
assert.equal(api.recent()[0].area,'atlas/test');
api.report('vm/error',vm.runInContext("new Error('inside vm')",context));
assert.equal(api.recent()[1].message,'inside vm');
const snapshot=api.recent();
snapshot.pop();
assert.equal(api.recent().length,2,'snapshot must not expose the internal array');
for(let i=0;i<60;i++)api.report('test',String(i));
assert.equal(api.recent().length,50,'diagnostics must remain bounded');
assert.equal(logged.length,62);
console.log('Diagnostics tests passed');
